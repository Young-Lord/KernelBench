"""Validate the MUSA evaluation JSON against the schemas in musa_operator_eval/schemas.

Guide §4.8 wants every companion file to pass a schema before it is committed,
because that is the cheap way to stop hand-written content from drifting. This is
that check, and it has to work on a machine with nothing but the standard library
installed -- the repository's dependency convention is stdlib plus numpy, so the
validator carries its own small JSON Schema subset rather than requiring
`jsonschema`. When `jsonschema` happens to be installed it is used instead, so the
result can be cross-checked against a full implementation.

Supported keywords: local `$ref` into `$defs`, type, const, enum, required,
properties, additionalProperties (false or a schema), items, minItems, maxItems,
uniqueItems, minLength, maxLength, pattern, minimum, maximum, minProperties,
allOf, anyOf, not, if/then/else.

    # every artifact in this repository
    python3 musa_operator_eval/tools/validate_schemas.py --all

    # one file, kind inferred from its name
    python3 musa_operator_eval/tools/validate_schemas.py musa_operator_eval/tasks/kb_l1_97_a/task.json

    # force a kind, which is how a hidden case manifest is checked
    python3 musa_operator_eval/tools/validate_schemas.py --kind case_manifest \
        musa_operator_eval/private/sdpa_forward_b_v0/cases.private.json

Exit codes: 0 all valid, 1 at least one document invalid, 2 bad usage.

Note on the hidden manifest: §4.3 fixes the `tag` vocabulary for both the public
and the hidden case lists, and the hidden manifest generated by
tools/make_private_manifest.py currently labels its gap cases with free text
("head_dim_beyond_fused_bound" and so on). Point this tool at that file and it
will say so; the fix belongs in the generator, not here.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any, List, Optional


ROOT = Path(__file__).resolve().parents[1]
SCHEMA_DIR = ROOT / "schemas"

# The document root in a validation message. Spelled with chr() because a bare
# dollar sign inside an f-string expression is easy for other tooling to mangle.
DOCUMENT_ROOT = chr(36)

# Kind -> schema file. The kind is what `--kind` takes and what the filename
# heuristic resolves to; keeping it in one table is what stops the two from
# disagreeing.
SCHEMAS = {
    "task_contract": "task_contract.schema.json",
    "semantics_contract": "semantics_contract.schema.json",
    "case_manifest": "case_manifest.schema.json",
    "baseline": "baseline.schema.json",
    "environment_snapshot": "environment_snapshot.schema.json",
    "evaluation_report": "evaluation_report.schema.json",
}


class SchemaError(ValueError):
    """Raised for a malformed schema, which is a bug in this repository."""


def load_schema(kind: str) -> dict:
    if kind not in SCHEMAS:
        raise SchemaError(f"unknown kind {kind!r}; choose from {sorted(SCHEMAS)}")
    return json.loads((SCHEMA_DIR / SCHEMAS[kind]).read_text(encoding="utf-8"))


# ---------------------------------------------------------------------------
# Minimal JSON Schema engine
# ---------------------------------------------------------------------------

_TYPE_CHECKS = {
    "object": lambda value: isinstance(value, dict),
    "array": lambda value: isinstance(value, list),
    "string": lambda value: isinstance(value, str),
    "integer": lambda value: isinstance(value, int) and not isinstance(value, bool),
    "number": lambda value: isinstance(value, (int, float)) and not isinstance(value, bool),
    "boolean": lambda value: isinstance(value, bool),
    "null": lambda value: value is None,
}


def _type_name(value: Any) -> str:
    if isinstance(value, bool):
        return "boolean"
    if isinstance(value, dict):
        return "object"
    if isinstance(value, list):
        return "array"
    if isinstance(value, str):
        return "string"
    if isinstance(value, int):
        return "integer"
    if isinstance(value, float):
        return "number"
    if value is None:
        return "null"
    return type(value).__name__


def _resolve_ref(root: dict, reference: str) -> dict:
    if not reference.startswith("#/"):
        raise SchemaError(f"only local references are supported, got {reference!r}")
    node: Any = root
    for part in reference[2:].split("/"):
        part = part.replace("~1", "/").replace("~0", "~")
        if not isinstance(node, dict) or part not in node:
            raise SchemaError(f"unresolvable reference {reference!r}")
        node = node[part]
    if not isinstance(node, dict):
        raise SchemaError(f"reference {reference!r} does not point at a schema")
    return node


def _matches(instance: Any, schema: dict, root: dict, path: str) -> bool:
    """Whether `instance` satisfies `schema`, discarding the reasons."""
    return not _collect(instance, schema, root, path)


def _collect(instance: Any, schema: dict, root: dict, path: str) -> List[str]:
    errors: List[str] = []

    if "$ref" in schema:
        target = _resolve_ref(root, schema["$ref"])
        # 2020-12 applies $ref alongside sibling keywords; the schemas here never
        # mix them, but dropping $ref and continuing keeps that true either way.
        remainder = {key: value for key, value in schema.items() if key != "$ref"}
        errors.extend(_collect(instance, target, root, path))
        if remainder:
            errors.extend(_collect(instance, remainder, root, path))
        return errors

    for subschema in schema.get("allOf", []):
        errors.extend(_collect(instance, subschema, root, path))

    if "anyOf" in schema:
        if not any(_matches(instance, option, root, path) for option in schema["anyOf"]):
            errors.append(f"{path}: value matches none of the alternatives in anyOf")

    if "not" in schema:
        if _matches(instance, schema["not"], root, path):
            errors.append(f"{path}: value matches a schema it must not match")

    if "if" in schema:
        branch = "then" if _matches(instance, schema["if"], root, path) else "else"
        if branch in schema:
            errors.extend(_collect(instance, schema[branch], root, path))

    expected = schema.get("type")
    if expected is not None:
        choices = expected if isinstance(expected, list) else [expected]
        if not any(_TYPE_CHECKS[choice](instance) for choice in choices):
            return [f"{path}: expected type {expected}, got {_type_name(instance)}"] + errors

    if "const" in schema and instance != schema["const"]:
        errors.append(f"{path}: expected {schema['const']!r}, got {instance!r}")
    if "enum" in schema and instance not in schema["enum"]:
        errors.append(f"{path}: {instance!r} is not one of {schema['enum']!r}")

    if isinstance(instance, str):
        if len(instance) < schema.get("minLength", 0):
            errors.append(f"{path}: shorter than minLength {schema['minLength']}")
        if "maxLength" in schema and len(instance) > schema["maxLength"]:
            errors.append(f"{path}: longer than maxLength {schema['maxLength']}")
        if "pattern" in schema and re.search(schema["pattern"], instance) is None:
            errors.append(f"{path}: does not match {schema['pattern']!r}")

    if isinstance(instance, (int, float)) and not isinstance(instance, bool):
        if "minimum" in schema and instance < schema["minimum"]:
            errors.append(f"{path}: {instance} is below minimum {schema['minimum']}")
        if "maximum" in schema and instance > schema["maximum"]:
            errors.append(f"{path}: {instance} is above maximum {schema['maximum']}")

    if isinstance(instance, list):
        if len(instance) < schema.get("minItems", 0):
            errors.append(f"{path}: fewer than {schema['minItems']} items")
        if "maxItems" in schema and len(instance) > schema["maxItems"]:
            errors.append(f"{path}: more than {schema['maxItems']} items")
        if schema.get("uniqueItems"):
            encoded = [json.dumps(item, sort_keys=True) for item in instance]
            if len(encoded) != len(set(encoded)):
                errors.append(f"{path}: items are not unique")
        if "items" in schema:
            for index, item in enumerate(instance):
                errors.extend(_collect(item, schema["items"], root, f"{path}[{index}]"))

    if isinstance(instance, dict):
        if len(instance) < schema.get("minProperties", 0):
            errors.append(f"{path}: fewer than {schema['minProperties']} properties")
        for key in schema.get("required", []):
            if key not in instance:
                errors.append(f"{path}: missing required property {key!r}")
        properties = schema.get("properties", {})
        additional = schema.get("additionalProperties", True)
        for key, value in instance.items():
            child_path = f"{path}.{key}"
            if key in properties:
                errors.extend(_collect(value, properties[key], root, child_path))
            elif additional is False:
                errors.append(f"{path}: unexpected property {key!r}")
            elif isinstance(additional, dict):
                errors.extend(_collect(value, additional, root, child_path))
    return errors


def validate_instance_stdlib(instance: Any, kind: str) -> List[str]:
    schema = load_schema(kind)
    return _collect(instance, schema, schema, DOCUMENT_ROOT)


# ---------------------------------------------------------------------------
# Cross-field rules the schema cannot express
# ---------------------------------------------------------------------------

def business_errors(instance: dict, kind: str) -> List[str]:
    errors: List[str] = []

    if kind == "case_manifest":
        seen: set = set()
        gaps = 0
        reasons: set = set()
        for index, case in enumerate(instance.get("cases", [])):
            case_id = case.get("case_id")
            if case_id in seen:
                errors.append(f"cases[{index}].case_id: duplicate {case_id!r}")
            seen.add(case_id)
            gap = case.get("library_gap")
            if gap is not None:
                gaps += 1
                reasons.add(gap.get("reason"))
        if instance.get("visibility") == "private" and instance.get("tier") == "B_library":
            if gaps < 3:
                errors.append(f"cases: a private B manifest needs at least 3 library gaps, found {gaps}")
            if not reasons:
                errors.append("cases: a private B manifest carries no library gap with a reason")

    # §4.3 also asks a hidden gap set to cover at least two reason categories, and
    # that rule is deliberately not enforced here. It is a statement about a task
    # contract and a case list together -- a task that cannot reach a second
    # category is allowed one, if its contract records why -- and a validator that
    # sees one document at a time cannot tell the two apart. It is enforced where
    # both are in scope, in `make_private_manifest.py`.

    if kind == "baseline":
        declared = set(instance.get("implementations", []))
        for index, row in enumerate(instance.get("results", [])):
            implementation = row.get("implementation")
            if implementation not in declared:
                errors.append(
                    f"results[{index}].implementation: {implementation!r} is not in implementations"
                )
    return errors


# ---------------------------------------------------------------------------
# Document-level entry points
# ---------------------------------------------------------------------------

def _jsonschema_errors(instance: Any, schema: dict) -> Optional[List[str]]:
    try:
        import jsonschema  # type: ignore
    except ImportError:
        return None
    validator = jsonschema.Draft202012Validator(schema)
    messages: List[str] = []
    for error in validator.iter_errors(instance):
        location = "/".join(str(part) for part in error.absolute_path)
        prefix = location if location else DOCUMENT_ROOT
        messages.append(prefix + ": " + error.message)
    return messages


def validate_instance(instance: Any, kind: str, engine: str = "auto") -> List[str]:
    schema = load_schema(kind)
    if engine == "stdlib":
        errors = _collect(instance, schema, schema, DOCUMENT_ROOT)
    else:
        found = _jsonschema_errors(instance, schema)
        if found is None:
            if engine == "jsonschema":
                raise SchemaError("jsonschema is not installed; use --engine stdlib")
            errors = _collect(instance, schema, schema, DOCUMENT_ROOT)
        else:
            errors = found
    if isinstance(instance, dict):
        errors.extend(business_errors(instance, kind))
    return errors


def validate_document(path: Path, kind: Optional[str] = None, engine: str = "auto") -> List[str]:
    instance = json.loads(path.read_text(encoding="utf-8"))
    return validate_instance(instance, kind or classify(path), engine=engine)


def classify(path: Path) -> str:
    """Resolve a document to its schema kind from the filename.

    The names are the ones the repository actually uses, so the heuristic is a
    description of the convention rather than a guess.
    """
    name = path.name
    if name == "task.json":
        return "task_contract"
    if name == "semantics.json":
        return "semantics_contract"
    if name in ("public_cases.json", "cases.private.json") or name.startswith("cases."):
        return "case_manifest"
    if name == "baseline.json" or name.startswith("baseline."):
        return "baseline"
    if name.endswith(".public.json") or name.endswith(".full.json") or name.startswith("environment."):
        return "environment_snapshot"
    if "report" in name:
        return "evaluation_report"
    raise SchemaError(f"cannot infer a schema kind from {path}; pass --kind")


def discover(root: Path) -> List[tuple]:
    """Every artifact of the six kinds that this repository actually ships.

    The hidden case manifest is deliberately absent: it is generated by
    tools/make_private_manifest.py and currently labels its gap cases with free
    text, which §4.3 does not allow. Validate it explicitly to see that.
    """
    found: List[tuple] = []
    found += [(path, "task_contract") for path in sorted(root.glob("tasks/*/task.json"))]
    found += [(path, "semantics_contract") for path in sorted(root.glob("tasks/*/semantics.json"))]
    found += [(path, "case_manifest") for path in sorted(root.glob("tasks/*/public_cases.json"))]
    found += [(path, "environment_snapshot") for path in sorted(root.glob("environments/*.public.json"))]
    found += [(path, "baseline") for path in sorted(root.glob("private/*/baseline.json"))]
    found += [(path, "environment_snapshot") for path in sorted(root.glob("private/environments/*.full.json"))]
    return found


def _display(path: Path, root: Path) -> str:
    try:
        return str(path.resolve().relative_to(root))
    except ValueError:
        return str(path)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("path", nargs="?", type=Path, help="a JSON document to validate")
    parser.add_argument("--kind", choices=sorted(SCHEMAS), help="force the schema kind")
    parser.add_argument("--all", action="store_true", help="validate every artifact the repository ships")
    parser.add_argument(
        "--engine", choices=["auto", "stdlib", "jsonschema"], default="auto",
        help="auto uses jsonschema when installed and the built-in engine otherwise",
    )
    parser.add_argument("--quiet", action="store_true", help="only print failures")
    args = parser.parse_args()

    if args.all:
        documents = discover(ROOT)
    elif args.path is not None:
        documents = [(args.path, args.kind)]
    else:
        parser.error("give a path or --all")

    failures = 0
    checked = 0
    for path, kind in documents:
        checked += 1
        try:
            errors = validate_document(path, kind, engine=args.engine)
        except (SchemaError, json.JSONDecodeError, OSError) as error:
            failures += 1
            print(f"FAIL {_display(path, ROOT)}: {type(error).__name__}: {error}")
            continue
        if errors:
            failures += 1
            print(f"FAIL {_display(path, ROOT)}")
            for error in errors:
                print(f"  {error}")
        elif not args.quiet:
            print(f"ok   {_display(path, ROOT)}")

    print(f"\n{checked - failures}/{checked} valid")
    return 1 if failures else 0


if __name__ == "__main__":
    raise SystemExit(main())
